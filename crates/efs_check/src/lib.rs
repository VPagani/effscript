//! In-process type checking of EffScript projects with tsrs.
//!
//! Every `.efs` file is compiled to TypeScript and laid over the real file system at the
//! path its build output would have (`foo.efs` becomes `foo.ts`). A tsrs `Program` is
//! built from the project's `tsconfig.json` plus those virtual files, and positions in
//! diagnostics and hovers are mapped back to the EffScript source through the span map.

pub mod effect_tsgo;

use std::collections::{BTreeMap, HashMap};
use std::path::{Path, PathBuf};
use std::sync::Arc;

use efs_codegen::Output;
use efs_syntax::{LineIndex, Span};
use tsrs_compiler::Program;
use tsrs_core::P;
use tsrs_core::context::Context;
use tsrs_vfs::FS;

/// A project: the directory that holds `tsconfig.json` and the `.efs` files under it.
#[derive(Clone, Debug)]
pub struct Workspace {
    pub root: PathBuf,
    pub tsconfig: Option<PathBuf>,
    pub codegen: efs_codegen::Options,
}

const SKIP_DIRS: &[&str] = &["node_modules", "target", "dist", "build", ".git"];

impl Workspace {
    /// Finds the nearest `tsconfig.json` at or above `start`.
    pub fn discover(start: &Path) -> Workspace {
        let start = std::fs::canonicalize(start).unwrap_or_else(|_| start.to_path_buf());
        let dir = if start.is_file() { start.parent().unwrap_or(&start).to_path_buf() } else { start.clone() };
        let mut cur = Some(dir.as_path());
        while let Some(d) = cur {
            let candidate = d.join("tsconfig.json");
            if candidate.is_file() {
                return Workspace { root: d.to_path_buf(), tsconfig: Some(candidate), codegen: Default::default() };
            }
            cur = d.parent();
        }
        Workspace { root: dir, tsconfig: None, codegen: Default::default() }
    }

    /// All `.efs` files under the root.
    pub fn efs_files(&self) -> Vec<PathBuf> {
        let mut out = Vec::new();
        walk(&self.root, &mut out);
        out.sort();
        out
    }
}

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else { return };
    for e in entries.flatten() {
        let p = e.path();
        let name = e.file_name();
        let name = name.to_string_lossy();
        if p.is_dir() {
            if !name.starts_with('.') && !SKIP_DIRS.contains(&name.as_ref()) {
                walk(&p, out);
            }
        } else if name.ends_with(".efs") {
            out.push(p);
        }
    }
}

/// The first line of every file `efs build` writes.
pub const GENERATED_HEADER_PREFIX: &str = "// Generated by efs from ";

/// The header `efs build` writes at the top of the output for `source_name`.
pub fn generated_header(source_name: &str) -> String {
    format!("{GENERATED_HEADER_PREFIX}{source_name}. Do not edit.\n")
}

/// Whether a `.ts` file on disk would be replaced by the output of an `.efs` file: true
/// when it exists and was not written by `efs build`.
pub fn is_handwritten(ts_path: &Path) -> bool {
    std::fs::read_to_string(ts_path).is_ok_and(|text| !text.starts_with(GENERATED_HEADER_PREFIX))
}

/// The TypeScript path generated for an EffScript file.
pub fn output_path(efs: &Path) -> PathBuf {
    efs.with_extension("ts")
}

fn path_str(p: &Path) -> String {
    p.to_string_lossy().replace('\\', "/")
}

#[derive(Clone, Debug)]
pub struct Compiled {
    pub path: PathBuf,
    pub src: String,
    pub output: Output,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Severity {
    Error,
    Warning,
    Suggestion,
}

/// A diagnostic located in an EffScript file (span in EffScript source) or a TypeScript file.
#[derive(Clone, Debug)]
pub struct CheckDiagnostic {
    pub file: Option<PathBuf>,
    pub span: Option<Span>,
    /// The file text the span refers to, for line/column conversion.
    pub text: Option<Arc<str>>,
    pub message: String,
    pub code: String,
    pub severity: Severity,
}

impl CheckDiagnostic {
    pub fn line_col(&self) -> Option<(u32, u32)> {
        let (span, text) = (self.span?, self.text.as_ref()?);
        Some(LineIndex::new(text).position(span.start))
    }
}

/// Compiled files plus a type-checked program built from them.
pub struct Session {
    pub workspace: Workspace,
    files: BTreeMap<PathBuf, Compiled>,
    /// Unsaved editor contents by path.
    overrides: HashMap<PathBuf, String>,
    program: Option<&'static Program>,
    virtual_files: Arc<HashMap<String, String>>,
}

struct ConfigHost {
    fs: Arc<dyn FS>,
    cwd: String,
}

impl tsrs_tsoptions::ParseConfigHost for ConfigHost {
    fn fs(&self) -> &dyn FS {
        &*self.fs
    }
    fn get_current_directory(&self) -> &str {
        &self.cwd
    }
}

fn base_fs() -> &'static dyn FS {
    static BASE: std::sync::OnceLock<Box<dyn FS>> = std::sync::OnceLock::new();
    &**BASE.get_or_init(|| Box::new(tsrs_vfs::bundled::wrap_fs(tsrs_vfs::osvfs::fs())))
}

const DEFAULT_TSCONFIG: &str = r#"{
  "compilerOptions": {
    "strict": true,
    "exactOptionalPropertyTypes": true,
    "target": "es2022",
    "module": "nodenext",
    "moduleResolution": "nodenext",
    "lib": ["es2022", "dom"],
    "skipLibCheck": true,
    "noEmit": true
  }
}"#;

impl Session {
    pub fn new(workspace: Workspace) -> Session {
        Session {
            workspace,
            files: BTreeMap::new(),
            overrides: HashMap::new(),
            program: None,
            virtual_files: Arc::new(HashMap::new()),
        }
    }

    /// Sets (or with `None` clears) the unsaved contents of a file.
    pub fn set_override(&mut self, path: &Path, text: Option<String>) {
        match text {
            Some(t) => self.overrides.insert(path.to_path_buf(), t),
            None => self.overrides.remove(path),
        };
        self.invalidate();
    }

    pub fn invalidate(&mut self) {
        if let Some(p) = self.program.take() {
            // SAFETY: nothing derived from the program outlives the calls that produced it.
            unsafe { tsrs_compiler::free_program(p) };
        }
        self.files.clear();
    }

    /// Compiles every `.efs` file in the workspace (and any open file outside it).
    pub fn compile(&mut self) -> &BTreeMap<PathBuf, Compiled> {
        if self.files.is_empty() {
            let mut paths = self.workspace.efs_files();
            for p in self.overrides.keys() {
                if !paths.contains(p) && p.extension().is_some_and(|e| e == "efs") {
                    paths.push(p.clone());
                }
            }
            for p in paths {
                let src = match self.overrides.get(&p) {
                    Some(t) => t.clone(),
                    None => std::fs::read_to_string(&p).unwrap_or_default(),
                };
                let mut output = efs_codegen::compile(&src, &self.workspace.codegen);
                let ts = output_path(&p);
                if is_handwritten(&ts) {
                    output.diagnostics.push(
                        efs_syntax::Diagnostic::error(
                            efs_syntax::Span::new(0, 0),
                            format!(
                                "the output of this file would replace the hand-written {}; rename one of them",
                                ts.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default()
                            ),
                        )
                        .with_code("conflict"),
                    );
                }
                self.files.insert(p.clone(), Compiled { path: p, src, output });
            }
        }
        &self.files
    }

    pub fn compiled(&mut self, path: &Path) -> Option<&Compiled> {
        self.compile();
        self.files.get(path)
    }

    fn program(&mut self) -> &'static Program {
        if let Some(p) = self.program {
            return p;
        }
        let program = self.build_program(|_| {});
        self.program = Some(program);
        program
    }

    /// Builds a program over the overlay, with `configure` applied to the compiler options.
    fn build_program(&mut self, configure: impl FnOnce(&mut tsrs_core::CompilerOptions)) -> &'static Program {
        self.compile();
        let mut virt = HashMap::new();
        for c in self.files.values() {
            virt.insert(path_str(&output_path(&c.path)), c.output.code.clone());
        }
        let root = path_str(&self.workspace.root);
        let tsconfig_path =
            self.workspace.tsconfig.as_ref().map(|p| path_str(p)).unwrap_or_else(|| format!("{root}/tsconfig.json"));
        if self.workspace.tsconfig.is_none() {
            virt.insert(tsconfig_path.clone(), DEFAULT_TSCONFIG.to_string());
        }
        let virt = Arc::new(virt);
        self.virtual_files = virt.clone();
        let base = base_fs();
        let (v1, v2, v3) = (virt.clone(), virt.clone(), virt.clone());
        let fs = tsrs_vfs::wrapvfs::wrap(
            base,
            tsrs_vfs::wrapvfs::Replacements {
                file_exists: Some(Box::new(move |p| v1.contains_key(p) || base.file_exists(p))),
                read_file: Some(Box::new(move |p| v2.get(p).cloned().or_else(|| base.read_file(p)))),
                stat: Some(Box::new(
                    move |p| if v3.contains_key(p) { base.stat(&root_dir_of(p)) } else { base.stat(p) },
                )),
                ..Default::default()
            },
        );
        let fs: Arc<dyn FS> = Arc::new(fs);
        let host = ConfigHost { fs: fs.clone(), cwd: root.clone() };
        let (parsed, _errors) =
            tsrs_tsoptions::get_parsed_command_line_of_config_file(&tsconfig_path, None, None, &host, None);
        let parsed = parsed.unwrap_or_else(|| {
            tsrs_tsoptions::new_parsed_command_line(
                P::new(Default::default()),
                Vec::new(),
                Vec::new(),
                tsrs_core::tspath::ComparePathsOptions::default(),
            )
        });
        let options = parsed.compiler_options().unwrap_or_else(|| P::new(Default::default()));
        let mut options = (*options).clone();
        configure(&mut options);
        let options = P::new(options);
        let mut names: Vec<String> = parsed.file_names().to_vec();
        for k in virt.keys() {
            if k.ends_with(".ts") && !names.contains(k) {
                names.push(k.clone());
            }
        }
        let config = tsrs_tsoptions::new_parsed_command_line(
            options,
            names,
            Vec::new(),
            tsrs_core::tspath::ComparePathsOptions::default(),
        );
        let host = tsrs_compiler::new_compiler_host(&root, fs, &tsrs_vfs::bundled::lib_path(), None, None, None);
        tsrs_compiler::new_program(tsrs_compiler::ProgramOptions::new(P::new(config), host))
    }

    /// Declaration files (`.d.ts`) for every EffScript file, by source path. Types are
    /// inferred by tsrs from the whole program, so the files need no annotations.
    pub fn declarations(&mut self) -> Vec<(PathBuf, String)> {
        use tsrs_core::Tristate;
        let program = self.build_program(|o| {
            o.declaration = Tristate::True;
            o.emit_declaration_only = Tristate::True;
            o.no_emit = Tristate::False;
            o.no_emit_on_error = Tristate::False;
            o.declaration_map = Tristate::False;
            o.source_map = Tristate::False;
            o.out_dir = String::new();
            o.declaration_dir = String::new();
            o.composite = Tristate::False;
            o.incremental = Tristate::False;
        });
        let targets: Vec<_> =
            self.files.values().filter_map(|c| program.get_source_file(&path_str(&output_path(&c.path)))).collect();
        let written: std::sync::Mutex<Vec<(String, String)>> = std::sync::Mutex::new(Vec::new());
        let write = |name: &str, text: &str, _: &mut tsrs_compiler::WriteFileData| -> Result<(), String> {
            written.lock().unwrap().push((name.to_string(), text.to_string()));
            Ok(())
        };
        let ctx = Context::background();
        program.emit(
            &ctx,
            &tsrs_compiler::EmitOptions {
                target_source_files: Some(targets),
                emit_only: tsrs_compiler::EmitOnly::EmitOnlyDts,
                force_emit: true,
                write_file: Some(&write),
            },
        );
        let written = written.into_inner().unwrap();
        // SAFETY: nothing derived from this program is used after this point.
        unsafe { tsrs_compiler::free_program(program) };
        let mut out = Vec::new();
        for c in self.files.values() {
            let dts = path_str(&output_path(&c.path).with_extension("d.ts"));
            if let Some((_, text)) = written.iter().find(|(n, _)| *n == dts) {
                out.push((c.path.clone(), text.clone()));
            }
        }
        out
    }

    fn efs_for_virtual(&self, ts_path: &str) -> Option<&Compiled> {
        self.files.values().find(|c| path_str(&output_path(&c.path)) == ts_path)
    }

    /// EffScript syntax and codegen diagnostics for every file.
    pub fn efs_diagnostics(&mut self) -> Vec<CheckDiagnostic> {
        self.compile();
        let mut out = Vec::new();
        for c in self.files.values() {
            let text: Arc<str> = Arc::from(c.src.as_str());
            for d in &c.output.diagnostics {
                out.push(CheckDiagnostic {
                    file: Some(c.path.clone()),
                    span: Some(d.span),
                    text: Some(text.clone()),
                    message: d.message.clone(),
                    code: d.code.clone(),
                    severity: match d.severity {
                        efs_syntax::Severity::Error => Severity::Error,
                        efs_syntax::Severity::Warning => Severity::Warning,
                        efs_syntax::Severity::Info => Severity::Suggestion,
                    },
                });
            }
        }
        out
    }

    /// Type diagnostics from tsrs. With `efs_only`, only diagnostics in EffScript files are returned.
    pub fn type_diagnostics(&mut self, efs_only: bool) -> Vec<CheckDiagnostic> {
        let program = self.program();
        let ctx = Context::background();
        let mut raw = Vec::new();
        raw.extend(program.get_config_file_parsing_diagnostics());
        raw.extend(program.get_program_diagnostics());
        raw.extend(program.get_syntactic_diagnostics(&ctx, None));
        raw.extend(program.get_semantic_diagnostics(&ctx, None));
        raw.extend(program.get_global_diagnostics(&ctx));
        let mut out = Vec::new();
        let mut seen = std::collections::HashSet::new();
        for d in raw {
            let mut message = Vec::new();
            tsrs_compiler::diagnosticwriter::write_flattened_diagnostic_message(&mut message, d, "\n");
            let message = String::from_utf8_lossy(&message).into_owned();
            let severity = match d.category() {
                tsrs_diagnostics::Category::Error => Severity::Error,
                tsrs_diagnostics::Category::Warning => Severity::Warning,
                _ => Severity::Suggestion,
            };
            let code = format!("ts{}", d.code());
            let file = d.file();
            let (file_path, span, text) = match file {
                Some(sf) => {
                    let name = sf.file_name().to_string();
                    let start = d.pos().unwrap_or(0);
                    let len = d.len().unwrap_or(0);
                    if let Some(c) = self.efs_for_virtual(&name) {
                        let span = c.output.range_to_source(start, len);
                        (Some(c.path.clone()), span, Some(Arc::<str>::from(c.src.as_str())))
                    } else {
                        if efs_only {
                            continue;
                        }
                        let text: Arc<str> = Arc::from(sf.text());
                        (Some(PathBuf::from(name)), Some(Span::new(start, start + len)), Some(text))
                    }
                }
                None => {
                    if efs_only {
                        continue;
                    }
                    (None, None, None)
                }
            };
            if !seen.insert((file_path.clone(), span, message.clone())) {
                continue;
            }
            out.push(CheckDiagnostic { file: file_path, span, text, message, code, severity });
        }
        out
    }

    /// The type of the expression at `offset` in an EffScript file, formatted for display.
    pub fn hover(&mut self, path: &Path, offset: u32) -> Option<String> {
        let gen_pos = self.compiled(path)?.output.to_generated(offset)?;
        let program = self.program();
        let ts_path = path_str(&output_path(path));
        let sf = program.get_source_file(&ts_path)?;
        let ctx = Context::background();
        let node = tsrs_astnav::get_touching_property_name(sf, gen_pos);
        let mut checker = program.get_type_checker_for_file(&ctx, sf);
        let ty = checker.get_type_at_location(node);
        let text = checker.type_to_string_exported(ty);
        let c = self.files.get(path)?;
        let name = word_at(&c.src, offset);
        Some(match name {
            Some(n) => format!("{n}: {text}"),
            None => text,
        })
    }
}

impl Drop for Session {
    fn drop(&mut self) {
        self.invalidate();
    }
}

fn root_dir_of(p: &str) -> String {
    p.rsplit_once('/').map_or("/".to_string(), |(d, _)| if d.is_empty() { "/".into() } else { d.to_string() })
}

fn word_at(src: &str, offset: u32) -> Option<String> {
    let o = offset as usize;
    if o > src.len() {
        return None;
    }
    let is_word = |c: char| c.is_alphanumeric() || c == '_' || c == '$';
    let start = src[..o].char_indices().rev().take_while(|&(_, c)| is_word(c)).last().map_or(o, |(i, _)| i);
    let end = src[o..].char_indices().find(|&(_, c)| !is_word(c)).map_or(src.len(), |(i, _)| o + i);
    (end > start).then(|| src[start..end].to_string())
}
